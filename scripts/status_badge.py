#!/usr/bin/env python3
"""
Computes and writes the concentric-ring conjecture status badge.

Six raw fields (in each conjecture's frontmatter `status:` block) are the
single source of truth. This script derives two grades from them and
renders a self-contained inline SVG badge plus a plain-English caption.
Never hand-edit `status_badge:` -- it is regenerated by this script.

    statement_informal  ai | human
    statement_formal    open | ai | human
    statement_match     open | ai | human
    proof_informal      open | ai | human
    proof_review        ai | human            (vacuous once proof_formal != open)
    proof_formal        open | ai | human

A seventh field says which *way* the work points, and is optional:

    proof_direction     proves | refutes      (default: proves)

It is deliberately not a grade. The six fields above say how well
established the work is; direction says whether what is established is the
statement or its negation, and a machine-checked refutation is exactly as
strong an artifact as a machine-checked proof. So proof_direction never
enters sigma or pi -- it only recolours the badge (green ramp -> red ramp),
swaps the pi == 4 glyph from a tick to a cross, and changes the caption's
noun from "Proof" to "Refutation". Omitting it leaves every existing page's
badge byte-for-byte unchanged.

Dependency constraints (checked by validate()):
    statement_match  != open  requires  statement_formal != open
    proof_formal     != open  requires  statement_formal != open
    proof_direction == refutes  requires  proof_informal != open

Grading functions
------------------
sigma(s1, s2, s3) -- statement grade, 0..5:
    s2 == open                -> 1 if s1 == human else 0
    s2 != open, s3 == open    -> 2
    s2 != open, s3 == ai      -> 3
    s2 != open, s3 == human   -> 4 + (1 if s1 == human else 0)   # 4 or 5

pi(p1, p2, p3) -- proof grade, 0..4:
    p3 != open                -> 4
    p3 == open, p1 == open    -> 0
    otherwise                 -> 1 + (p1 == human) + (p2 == human)   # 1, 2, 3

pi ignores who wrote a *formal* proof (AI vs human): once there is a
machine-checked proof object, the kernel is the arbiter (de Bruijn
criterion), so proof_formal authorship is metadata/caption text, not a
colour.

Seal (de Bruijn-complete): pi == 4 and sigma >= 4.

Beyond the badge, every page carrying a `status:` block (leaves under c/ and
papers under papers/) also carries a required `status_summary` frontmatter
field and an `## Open obligations` body section (checked, never generated,
here). `statement_sha` is a hash of the page's `## Statement`
block: if it no longer matches what's on disk, the informal statement
changed since the formalization was last checked against it, so
`statement_match` is forced back to `open`, `statement_sha` is rewritten,
and `revision` is bumped -- a match can never be silently invalidated. Run
with `--check` (no writes) to use this as a CI gate.
"""

import hashlib
import re
import sys
from pathlib import Path

LEVELS3 = ("open", "ai", "human")
LEVELS2 = ("ai", "human")

# Roots scanned when no target is given on the command line. Both hold pages
# carrying the `status:`/`statement_sha`/`status_badge` contract: statements
# under c/, and papers under papers/ (the same tabs, the same hashed
# `## Statement` block). Hubs under p/ are deliberately absent: per
# /schema/, a hub carries no badge of its own, only an aggregate view over
# its children. Any page without a `status:` block is skipped anyway, so the
# exemption is about intent rather than mechanics -- adding a `status:` block
# to a hub should be a deliberate schema change, not something this script
# starts silently generating badges for.
DEFAULT_ROOTS = ("c", "papers")

FIELD_SPECS = {
    "statement_informal": LEVELS2,
    "statement_formal": LEVELS3,
    "statement_match": LEVELS3,
    "proof_informal": LEVELS3,
    "proof_review": LEVELS2,
    "proof_formal": LEVELS3,
}
FREE_TEXT_FIELDS = ("statement_by", "proof_by")

DIRECTIONS = ("proves", "refutes")
DEFAULT_DIRECTION = "proves"

# Optional graded-block fields: validated when present, defaulted when absent.
# Kept apart from FIELD_SPECS because that dict drives both the
# missing-field error and the monotonicity self-test, and direction is
# neither required nor ordered.
OPTIONAL_FIELD_SPECS = {"proof_direction": DIRECTIONS}

START_MARKER = "<!-- status:start -->"
END_MARKER = "<!-- status:end -->"

OBLIGATIONS_HEADING_RE = re.compile(r"^##\s+Open obligations\s*$", re.MULTILINE)
STATEMENT_BLOCK_RE = re.compile(
    r"^##\s+Statement\s*\n(.*?)(?=^##\s+\S|\Z)", re.MULTILINE | re.DOTALL
)


def compute_sigma(s1, s2, s3):
    if s2 == "open":
        return 1 if s1 == "human" else 0
    if s3 == "open":
        return 2
    if s3 == "ai":
        return 3
    return 4 + (1 if s1 == "human" else 0)


def compute_pi(p1, p2, p3):
    if p3 != "open":
        return 4
    if p1 == "open":
        return 0
    return 1 + (1 if p1 == "human" else 0) + (1 if p2 == "human" else 0)


def validate(status, filename):
    for field, allowed in FIELD_SPECS.items():
        if field not in status:
            raise ValueError(f"{filename}: missing status.{field}")
        if status[field] not in allowed:
            raise ValueError(
                f"{filename}: status.{field} = {status[field]!r} not in {allowed}"
            )
    if status["statement_match"] != "open" and status["statement_formal"] == "open":
        raise ValueError(
            f"{filename}: statement_match={status['statement_match']!r} requires "
            f"statement_formal != open (nothing to match against)"
        )
    if status["proof_formal"] != "open" and status["statement_formal"] == "open":
        raise ValueError(
            f"{filename}: proof_formal={status['proof_formal']!r} requires "
            f"statement_formal != open (a formal proof is a proof of a formal statement)"
        )
    for field, allowed in OPTIONAL_FIELD_SPECS.items():
        if field in status and status[field] not in allowed:
            raise ValueError(
                f"{filename}: status.{field} = {status[field]!r} not in {allowed}"
            )
    if direction_of(status) == "refutes" and status["proof_informal"] == "open":
        raise ValueError(
            f"{filename}: proof_direction='refutes' requires proof_informal != open "
            f"(there is no refutation without a proof of one)"
        )


def direction_of(status):
    return status.get("proof_direction") or DEFAULT_DIRECTION


_DASH = {"open": "1,3", "ai": "5,3", "human": None}
_GLYPH = {0: "–", 1: "·", 2: "•", 3: "●", 4: "✓"}
# Same shapes at pi 0-3 -- at those grades the direction lives in the
# caption, not the glyph, because a drafted-but-unformalized refutation has
# no more visual weight to spend than a drafted proof. At pi == 4 the tick
# becomes a cross, which is the one channel that survives greyscale.
_GLYPH_REFUTED = {**_GLYPH, 4: "✗"}


def glyph_for(pi, direction=DEFAULT_DIRECTION):
    return (_GLYPH_REFUTED if direction == "refutes" else _GLYPH)[pi]

_LABEL = {"open": "none yet", "ai": "AI", "human": "human"}

# A full absolute URL, not a relative or root-relative ('/...') path.
# Two things rule those out: (1) Quarto's HTML post-processing rewrites
# root-relative hrefs inside raw embedded HTML incorrectly (turns
# '/open-problems/index.html' into '../open-problems/index.html', a 404);
# (2) the SAME status_badge string this script writes into a conjecture's
# frontmatter is also reused verbatim by Quarto's listing table on that
# conjecture's (shallower) topic-listing page, so no single relative path
# can be correct in both places at once. An absolute URL is immune to
# both problems since it's never relative-resolved.
#
# Trade-off: clicking a badge under `quarto preview` jumps to the live
# production site rather than the local preview.
LEGEND_URL = "https://crypto-conjura.github.io/open-problems/status-legend/index.html#status-legend"


def render_badge_svg(status, legend_url=LEGEND_URL):
    sigma = compute_sigma(
        status["statement_informal"], status["statement_formal"], status["statement_match"]
    )
    pi = compute_pi(status["proof_informal"], status["proof_review"], status["proof_formal"])
    sealed = pi == 4 and sigma >= 4

    dash = _DASH[status["statement_match"]]
    dash_attr = f" stroke-dasharray='{dash}'" if dash else ""
    # The seal is kept for a sealed refutation: it means de-Bruijn-complete,
    # not "true". A machine-checked refutation of a conjecture is as finished
    # a piece of work as a machine-checked proof of one.
    seal_el = (
        "<circle cx='16' cy='16' r='15' fill='none' stroke-width='1.5' class='cj-seal'/>"
        if sealed
        else ""
    )
    direction = direction_of(status)
    # A modifier class rather than a second set of ring/disc classes, so the
    # grade classes stay the single encoding of sigma and pi and the red ramp
    # is one override block per theme.
    refuted_class = " cj-refuted" if direction == "refutes" else ""
    glyph = glyph_for(pi, direction)
    title = render_caption(status)

    # NOTE: attribute values use single quotes throughout, matching the
    # site's convention for HTML embedded in a double-quoted YAML string
    # (see e.g. the cj-badge spans elsewhere) -- double quotes here would
    # prematurely terminate the YAML string value.
    #
    # NOTE: deliberately no <title> element inside the <svg>. When this
    # SVG is wrapped in the <a> below, Quarto/pandoc's raw-HTML-block
    # parser mis-parses <a><svg><title>...</title><circle/>...</svg></a>
    # and silently drops every sibling of <title> (the circles/text) from
    # the rendered output -- reproduced directly against pandoc, not a
    # caching artifact. Dropping <title> avoids the bug entirely; the
    # <a>'s aria-label below carries the same text for accessibility.
    svg = (
        f"<svg class='cj-status-badge{refuted_class}' viewBox='0 0 32 32' "
        "width='28' height='28' "
        "xmlns='http://www.w3.org/2000/svg' role='img'>"
        f"{seal_el}"
        f"<circle cx='16' cy='16' r='13' fill='none' stroke-width='4' "
        f"class='cj-ring-{sigma}'{dash_attr}/>"
        f"<circle cx='16' cy='16' r='8' class='cj-disc-{pi}'/>"
        f"<text x='16' y='17' text-anchor='middle' dominant-baseline='central' "
        f"class='cj-glyph' font-size='9'>{glyph}</text>"
        "</svg>"
    )
    # Wrapped in a link to the legend so the symbol itself is clickable --
    # aria-label carries the caption since a screen reader announces link
    # text, not (necessarily) an inner SVG's contents, for an anchor-wrapped
    # image, and since the <title> workaround above removed the SVG's own
    # accessible name.
    return (
        f"<a href='{legend_url}' class='cj-status-link' aria-label='{title} "
        "Click for the status badge legend.'>"
        f"{svg}"
        "</a>"
    )


def render_caption(status):
    s1, s2, s3 = status["statement_informal"], status["statement_formal"], status["statement_match"]
    p1, p2, p3 = status["proof_informal"], status["proof_review"], status["proof_formal"]

    if s2 == "open":
        stmt = f"Statement: {_LABEL[s1]}-written, not yet formalized."
    else:
        stmt = f"Statement: {_LABEL[s1]}-written, {_LABEL[s2]}-formalized"
        if s3 == "open":
            stmt += ", not yet matched against the informal statement."
        else:
            stmt += f", {_LABEL[s3]}-matched against the informal statement."

    # The caption is also the <a>'s aria-label, so for a refutation this is
    # the channel that says so in words -- the only one at pi < 4, where the
    # glyph is direction-neutral and colour is all that is left.
    noun = "Refutation" if direction_of(status) == "refutes" else "Proof"

    if p3 != "open":
        proof = f"{noun}: machine-checked ({_LABEL[p3]}-formalized)."
    elif p1 == "open":
        # Unreachable for a refutation: validate() rejects that combination.
        proof = f"{noun}: open -- no attempt yet."
    else:
        # proof_review is a 2-level field (ai|human) whose floor ("ai") means
        # "not yet reviewed by a human" -- it does NOT assert that an AI
        # reviewer actually looked at it, only that no human has. Only say
        # "reviewed" once a human actually has; otherwise say so plainly.
        review = "human-reviewed" if p2 == "human" else "not yet independently reviewed"
        proof = f"{noun}: {_LABEL[p1]} draft, {review}, not yet formalized."

    return f"{stmt} {proof}"


def self_test():
    checked = 0
    directions_checked = 0
    rejected = 0
    for s1 in LEVELS2:
        for s2 in LEVELS3:
            for s3 in LEVELS3:
                if s3 != "open" and s2 == "open":
                    continue
                for p1 in LEVELS3:
                    for p2 in LEVELS2:
                        for p3 in LEVELS3:
                            if p3 != "open" and s2 == "open":
                                continue
                            base = dict(
                                statement_informal=s1,
                                statement_formal=s2,
                                statement_match=s3,
                                proof_informal=p1,
                                proof_review=p2,
                                proof_formal=p3,
                            )
                            sigma0 = compute_sigma(s1, s2, s3)
                            pi0 = compute_pi(p1, p2, p3)
                            for field, levels in FIELD_SPECS.items():
                                idx = levels.index(base[field])
                                if idx + 1 >= len(levels):
                                    continue
                                raised = dict(base)
                                raised[field] = levels[idx + 1]
                                if (
                                    raised["statement_match"] != "open"
                                    and raised["statement_formal"] == "open"
                                ):
                                    continue
                                if (
                                    raised["proof_formal"] != "open"
                                    and raised["statement_formal"] == "open"
                                ):
                                    continue
                                sigma1 = compute_sigma(
                                    raised["statement_informal"],
                                    raised["statement_formal"],
                                    raised["statement_match"],
                                )
                                pi1 = compute_pi(
                                    raised["proof_informal"],
                                    raised["proof_review"],
                                    raised["proof_formal"],
                                )
                                assert sigma1 >= sigma0, (base, field, sigma0, sigma1)
                                assert pi1 >= pi0, (base, field, pi0, pi1)
                            checked += 1
                            # Direction is not a grade: flipping it must move
                            # neither sigma nor pi, and must leave the ring
                            # and disc classes -- the encoding of both grades
                            # -- untouched. Only the modifier class, the
                            # pi == 4 glyph and the caption's noun may differ.
                            if p1 != "open":
                                refuted = dict(base, proof_direction="refutes")
                                validate(refuted, "<self-test>")
                                assert compute_sigma(s1, s2, s3) == sigma0
                                assert compute_pi(p1, p2, p3) == pi0
                                proves_svg = render_badge_svg(base)
                                refuted_svg = render_badge_svg(refuted)
                                assert f"cj-ring-{sigma0}" in refuted_svg
                                assert f"cj-disc-{pi0}" in refuted_svg
                                assert "cj-refuted" in refuted_svg
                                assert "cj-refuted" not in proves_svg
                                assert ("✗" in refuted_svg) == (pi0 == 4)
                                assert "Refutation:" in render_caption(refuted)
                                directions_checked += 1
                            else:
                                # refutes with no informal proof is rejected,
                                # not silently rendered.
                                try:
                                    validate(dict(base, proof_direction="refutes"), "<self-test>")
                                except ValueError:
                                    rejected += 1
                                else:
                                    raise AssertionError(
                                        f"refutes accepted with proof_informal=open: {base}"
                                    )
    print(f"self-test OK: {checked} constraint-valid tuples, monotone in every field")
    print(
        f"self-test OK: {directions_checked} refutable tuples carry the same grades "
        f"in both directions, {rejected} open-proof tuples rejected as refutations"
    )


_STATUS_BLOCK_RE = re.compile(
    r"^status:\s*\n((?:[ \t]+\S.*\n?)+)", re.MULTILINE
)
_KV_RE = re.compile(r"^[ \t]+([A-Za-z_]+):\s*(.*)$")


def parse_status_block(frontmatter, filename):
    m = _STATUS_BLOCK_RE.search(frontmatter)
    if not m:
        return None
    status = {}
    for line in m.group(1).splitlines():
        kv = _KV_RE.match(line)
        if not kv:
            continue
        key, val = kv.group(1), kv.group(2).strip()
        if val.startswith('"') and val.endswith('"'):
            val = val[1:-1]
        status[key] = val
    for field in FIELD_SPECS:
        if field not in status:
            raise ValueError(f"{filename}: status block missing '{field}'")
    for field in FREE_TEXT_FIELDS:
        status.setdefault(field, "")
    status.setdefault("proof_direction", DEFAULT_DIRECTION)
    return status


def get_scalar_field(frontmatter, field):
    m = re.search(rf"^{field}:\s*(.*)$", frontmatter, re.MULTILINE)
    if not m:
        return None
    val = m.group(1).strip()
    if val.startswith('"') and val.endswith('"') and len(val) >= 2:
        val = val[1:-1]
    return val


def set_scalar_field(frontmatter, field, value, quote):
    stripped = re.sub(rf"^{field}:.*\n?", "", frontmatter, flags=re.MULTILINE)
    rendered = f'"{value}"' if quote else str(value)
    return stripped.rstrip("\n") + "\n" + f"{field}: {rendered}" + "\n"


def normalize_statement_text(text):
    lines = [line.rstrip() for line in text.split("\n")]
    normalized_lines = []
    blank_run = 0
    for line in lines:
        if line == "":
            blank_run += 1
            if blank_run > 1:
                continue
        else:
            blank_run = 0
        normalized_lines.append(line)
    return "\n".join(normalized_lines).strip("\n")


# The artifact row at the top of the tab and the `### Sources` list at the
# bottom are furniture, not the statement. They are stripped before hashing so
# that adding an artifact link, or re-siting the source list, cannot reset
# `statement_match` and bump `revision` -- which would read as "somebody
# reworded the conjecture" when nobody did. A wording edit inside the statement
# itself still changes the hash, which is the whole point of the mechanism.
_ARTIFACT_ROW_RE = re.compile(
    r"^(?:\[View PDF\]\(|View PDF — )[^\n]*$", re.MULTILINE
)
_TRAILING_SOURCES_RE = re.compile(r"\n###\s+Sources\s*\n.*\Z", re.DOTALL)


def statement_text_for_hash(block):
    """The statement prose alone, with the artifact row and Sources removed."""
    block = _TRAILING_SOURCES_RE.sub("", block)
    block = _ARTIFACT_ROW_RE.sub("", block)
    return normalize_statement_text(block)


def compute_statement_sha(body):
    m = STATEMENT_BLOCK_RE.search(body)
    if not m:
        return None
    normalized = statement_text_for_hash(m.group(1))
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()


def process_file(path, check=False):
    text = path.read_text(encoding="utf-8")
    fm_match = re.match(r"^---\n(.*?\n)---\n", text, re.DOTALL)
    if not fm_match:
        return False, []
    frontmatter = fm_match.group(1)
    body = text[fm_match.end() :]

    status = parse_status_block(frontmatter, path)
    if status is None:
        return False, []

    errors = []
    if not (get_scalar_field(frontmatter, "status_summary") or "").strip():
        errors.append(f"{path}: missing or empty status_summary")
    if not OBLIGATIONS_HEADING_RE.search(body):
        errors.append(f"{path}: missing an '## Open obligations' section in the body")

    computed_sha = compute_statement_sha(body)
    if computed_sha is None:
        errors.append(f"{path}: no '## Statement' section found to hash")
    else:
        existing_sha = get_scalar_field(frontmatter, "statement_sha")
        if existing_sha != computed_sha:
            if existing_sha:
                print(
                    f"WARNING: {path}: statement text changed since the last "
                    "recorded hash -- forcing statement_match to 'open', "
                    "rewriting statement_sha, bumping revision",
                    file=sys.stderr,
                )
                status["statement_match"] = "open"
                try:
                    revision = int(get_scalar_field(frontmatter, "revision") or "0") + 1
                except ValueError:
                    revision = 1
                frontmatter = set_scalar_field(frontmatter, "revision", revision, quote=False)
            frontmatter = set_scalar_field(frontmatter, "statement_sha", computed_sha, quote=True)

    validate(status, str(path))
    badge = render_badge_svg(status)
    caption = render_caption(status)

    new_frontmatter = re.sub(r"^status_badge:.*\n?", "", frontmatter, flags=re.MULTILINE)
    badge_line = f'status_badge: "{badge}"'
    new_frontmatter = new_frontmatter.rstrip("\n") + "\n" + badge_line + "\n"

    new_text = text[: fm_match.start(1)] + new_frontmatter + text[fm_match.end(1) :]

    body_block = f"{START_MARKER}\n{badge}\n\n*{caption}*\n{END_MARKER}"
    marker_re = re.compile(
        re.escape(START_MARKER) + r".*?" + re.escape(END_MARKER), re.DOTALL
    )
    if not marker_re.search(new_text):
        raise ValueError(
            f"{path}: no {START_MARKER} ... {END_MARKER} markers found in body"
        )
    new_text = marker_re.sub(body_block, new_text)

    changed = new_text != text
    if changed and not check:
        path.write_text(new_text, encoding="utf-8")
        print(f"updated {path}")
    elif changed and check:
        print(f"STALE: {path} would be updated by scripts/status_badge.py")
    return changed, errors


def main(argv):
    if "--self-test" in argv:
        self_test()
        return 0

    check = "--check" in argv
    targets = [a for a in argv if not a.startswith("--")] or list(DEFAULT_ROOTS)
    files = []
    for t in targets:
        p = Path(t)
        if p.is_dir():
            files.extend(sorted(p.glob("**/index.qmd")))
        elif p.is_file():
            files.append(p)

    changed = 0
    all_errors = []
    for f in files:
        try:
            did_change, errors = process_file(f, check=check)
        except ValueError as e:
            print(f"ERROR: {e}", file=sys.stderr)
            all_errors.append(str(e))
            continue
        all_errors.extend(errors)
        if did_change:
            changed += 1

    if check and changed:
        all_errors.append(
            f"{changed} file(s) are stale -- run scripts/status_badge.py to "
            "regenerate and commit the result"
        )

    verb = "would be " if check else ""
    print(f"{changed} file(s) {verb}updated out of {len(files)} scanned")

    if all_errors:
        for e in all_errors:
            print(f"ERROR: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
